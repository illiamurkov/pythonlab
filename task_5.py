a = float(input("введите число a: "))
b = float(input("введите число b: "))

if b == 0:
    print("деление на 0 запрещено - частное и остаток от деления не находим")
else:
    print (f"частное от деления чисел {a} и {b} = {a / b}")
    print (f"остаток от деления чисел {a} и {b} = {a % b}")

print (f"сумма чисел {a} и {b} = {a + b}")
print (f"разность чисел {a} и {b} = {a - b}")
print (f"произведение чисел {a} и {b} = {a * b}")
print (f"возведение числа {a} в степень {b} = {a ** b}")